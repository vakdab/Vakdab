import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(new URL('..', import.meta.url).pathname);
const entry = path.join(root, 'src/styles/app.css');
const output = path.join(root, 'src/styles/app.bundle.css');
const importedFiles = new Set();
const externalImports = [];

function readStylesheet(filePath) {
    const normalizedPath = path.resolve(filePath);
    if (importedFiles.has(normalizedPath)) return '';
    importedFiles.add(normalizedPath);

    const source = fs.readFileSync(normalizedPath, 'utf8');
    const directory = path.dirname(normalizedPath);
    return source.replace(/@import\s+(?:url\(\s*)?(['"])([^'"]+)\1\s*\)?\s*;/gi, (statement, quote, importPath) => {
        if (/^(?:https?:|data:|\/\/)/i.test(importPath)) {
            externalImports.push(statement);
            return '';
        }
        const cleanPath = importPath.split('?')[0].split('#')[0];
        const localPath = path.resolve(directory, cleanPath);
        if (!localPath.startsWith(path.join(root, 'src/styles') + path.sep)) {
            throw new Error(`Refusing to inline stylesheet outside src/styles: ${importPath}`);
        }
        return `\n/* Inlined from ${path.relative(root, localPath)} */\n${readStylesheet(localPath)}\n/* End ${path.relative(root, localPath)} */\n`;
    });
}

const inlinedStyles = readStylesheet(entry);
const bundled = [
    '/* Generated by scripts/build_css_bundle.mjs. Edit source CSS files, then regenerate. */',
    ...externalImports,
    inlinedStyles
].join('\n');

const normalizedBundle = bundled
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\n+$/, '\n');
fs.writeFileSync(output, normalizedBundle);
console.log(`Wrote ${path.relative(root, output)} from ${importedFiles.size} stylesheets (${fs.statSync(output).size} bytes).`);
