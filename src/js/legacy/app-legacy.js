function buildEffectOverlayHtml(type) {
  const rand = (min, max) => Math.random() * (max - min) + min;
  let n = 18, cls = "drop";
  if (type === "snow") {
    n = 16;
    cls = "flake";
  } else if (type === "sparks") {
    n = 14;
    cls = "spark";
  } else if (type === "hearts") {
    n = 12;
    cls = "heart";
  } else if (type === "bubbles") {
    n = 12;
    cls = "bubble";
  }
  let items = "";
  for (let i = 0; i < n; i++) {
    const left = rand(0, 100).toFixed(1);
    const delay = rand(0, 3).toFixed(2);
    const dur = type === "sparks" ? rand(1.4, 2.6).toFixed(2) : rand(1.1, 2.4).toFixed(2);
    if (type === "sparks") {
      const top = rand(0, 100).toFixed(1);
      items += `<span class="spark" style="left:${left}%;top:${top}%;animation-delay:${delay}s;animation-duration:${dur}s;"></span>`;
    } else {
      items += `<span class="${cls}" style="left:${left}%;animation-delay:${delay}s;animation-duration:${dur}s;"></span>`;
    }
  }
  return `<div class="effect-overlay effect-overlay--${type}">${items}</div>`;
}
